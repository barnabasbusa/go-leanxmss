//go:build ignore

// This program generates keccakf_scalar_arm64.s, Keccak-f[1600] on one state in
// the general-purpose registers, for arm64 CPUs without the SHA3 instructions.
// Run it from the repository's root:
//
//	go run _asm/keccakf_arm64_scalar.go
//
// The 24 rounds are unrolled. A lane lives in a register, and pi moves lanes by
// renaming registers, not by moving values. Theta's column parities go through
// the stack: 25 lanes and 3 temporaries take every register Go lets assembly use.
package main

import (
	"bytes"
	"fmt"
	"log"
	"os"
)

const out = "keccakf_scalar_arm64.s"

// regs are the registers the permutation uses: all but R18 (the platform
// register), R27 (the assembler's), R28 (g) and RSP. The epilogue recomputes R29
// from RSP, and R30, which the prologue saves at 0(RSP), is reloaded before RET.
var regs = []string{
	"R0", "R1", "R2", "R3", "R4", "R5", "R6", "R7", "R8", "R9",
	"R10", "R11", "R12", "R13", "R14", "R15", "R16", "R17",
	"R19", "R20", "R21", "R22", "R23", "R24", "R25", "R26", "R29", "R30",
}

var roundConstants = [24]uint64{
	0x0000000000000001, 0x0000000000008082, 0x800000000000808a, 0x8000000080008000,
	0x000000000000808b, 0x0000000080000001, 0x8000000080008081, 0x8000000000008009,
	0x000000000000008a, 0x0000000000000088, 0x0000000080008009, 0x000000008000000a,
	0x000000008000808b, 0x800000000000008b, 0x8000000000008089, 0x8000000000008003,
	0x8000000000008002, 0x8000000000000080, 0x000000000000800a, 0x800000008000000a,
	0x8000000080008081, 0x8000000000008080, 0x0000000080000001, 0x8000000080008008,
}

// rho[x][y] is the left rotation of lane (x, y).
var rho = [5][5]int{
	{0, 36, 3, 41, 18},
	{1, 44, 10, 45, 2},
	{62, 6, 43, 15, 61},
	{28, 55, 25, 21, 56},
	{27, 20, 39, 8, 14},
}

func lane(x, y int) int { return x + 5*y }

func main() {
	var b bytes.Buffer
	p := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }

	p("// Code generated by _asm/keccakf_arm64_scalar.go. DO NOT EDIT.")
	p("")
	p("//go:build arm64 && !purego")
	p("")
	p("#include \"textflag.h\"")
	p("")
	p("// func keccakF1600Scalar(s *[25]uint64)")
	p("TEXT ·keccakF1600Scalar(SB), NOSPLIT, $48-8")

	// at[i] is the register of lane i, free the three others.
	var at [25]string
	copy(at[:], regs)
	free := []string{regs[25], regs[26], regs[27]}

	p("\tMOVD\ts+0(FP), %s", free[0])
	for i := 0; i < 24; i += 2 {
		p("\tLDP\t%d(%s), (%s, %s)", 8*i, free[0], at[i], at[i+1])
	}
	p("\tMOVD\t%d(%s), %s", 8*24, free[0], at[24])

	for round, rc := range roundConstants {
		p("")
		p("\t// Round %d: theta's column parities, to the stack,", round)
		for x := range 5 {
			t := free[x%2]
			p("\tEOR\t%s, %s, %s", at[lane(x, 1)], at[lane(x, 0)], t)
			for y := 2; y < 5; y++ {
				p("\tEOR\t%s, %s, %s", at[lane(x, y)], t, t)
			}
			p("\tMOVD\t%s, %d(RSP)", t, 8+8*x)
		}

		p("\t// then D[x] = C[x-1] ^ rol(C[x+1], 1) into column x,")
		for x := range 5 {
			d, c := free[2*(x%2)], free[1]
			p("\tMOVD\t%d(RSP), %s", 8+8*((x+4)%5), d)
			p("\tMOVD\t%d(RSP), %s", 8+8*((x+1)%5), c)
			p("\tEOR\t%s@>63, %s, %s", c, d, d)
			for y := range 5 {
				p("\tEOR\t%s, %s, %s", d, at[lane(x, y)], at[lane(x, y)])
			}
		}

		p("\t// then rho, pi and chi, a row of the result at a time, and iota.")
		var next [25]string
		for y := range 5 {
			// Lane (x, y) of the result is chi of b[x], lane (x + 3y, x) rotated.
			var bx [5]string
			for x := range 5 {
				sx, sy := (x+3*y)%5, x
				r := at[lane(sx, sy)]
				if k := rho[sx][sy]; k != 0 {
					p("\tROR\t$%d, %s, %s", 64-k, r, r)
				}
				bx[x] = r
			}

			t0, t1, t2 := free[0], free[1], free[2]
			p("\tBIC\t%s, %s, %s", bx[1], bx[2], t0)
			p("\tEOR\t%s, %s, %s", bx[0], t0, t0)
			p("\tBIC\t%s, %s, %s", bx[2], bx[3], t1)
			p("\tEOR\t%s, %s, %s", bx[1], t1, t1)
			p("\tBIC\t%s, %s, %s", bx[3], bx[4], t2)
			p("\tEOR\t%s, %s, %s", bx[2], t2, t2)
			p("\tBIC\t%s, %s, %s", bx[4], bx[0], bx[2])
			p("\tEOR\t%s, %s, %s", bx[3], bx[2], bx[2])
			p("\tBIC\t%s, %s, %s", bx[0], bx[1], bx[3])
			p("\tEOR\t%s, %s, %s", bx[4], bx[3], bx[3])
			next[lane(0, y)], next[lane(1, y)], next[lane(2, y)] = t0, t1, t2
			next[lane(3, y)], next[lane(4, y)] = bx[2], bx[3]
			free = []string{bx[0], bx[1], bx[4]}

			if y == 0 {
				p("\tMOVD\t$0x%016x, %s", rc, free[0])
				p("\tEOR\t%s, %s, %s", free[0], t0, t0)
			}
		}

		at = next
	}

	p("")
	p("\tMOVD\ts+0(FP), %s", free[0])
	for i := 0; i < 24; i += 2 {
		p("\tSTP\t(%s, %s), %d(%s)", at[i], at[i+1], 8*i, free[0])
	}
	p("\tMOVD\t%s, %d(%s)", at[24], 8*24, free[0])
	p("\tMOVD\t0(RSP), R30 // The prologue saved the return address there.")
	p("\tRET")

	if err := os.WriteFile(out, b.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
}
